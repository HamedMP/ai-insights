import { createHash } from "node:crypto";
import type { Report } from "../schema/types.js";
import { createContext } from "./components.js";
import { formatDate, safeTimeZone } from "./format.js";
import { html, join, raw, type SafeHtml } from "./html.js";
import { SCRIPT } from "./script.js";
import { activitySection } from "./sections/activity.js";
import { collectAdvice, featuresSection, frictionSection, suggestionsSection } from "./sections/advice.js";
import { coverageSection } from "./sections/coverage.js";
import { matrixSection } from "./sections/matrix.js";
import { horizonSection, insightsPromptSection, winsSection, workSection } from "./sections/narrative.js";
import { overviewSection, rangeText, type NavItem } from "./sections/overview.js";
import { STYLES } from "./styles.js";
import { usageSection } from "./sections/usage.js";

const SCRIPT_HASH = createHash("sha256").update(SCRIPT).digest("base64");

/**
 * Nothing may load from anywhere: an escaping bug still cannot fetch a
 * resource or run an injected script, because only our script's hash runs.
 */
const CSP = `default-src 'none'; style-src 'unsafe-inline'; script-src 'sha256-${SCRIPT_HASH}'; img-src data:; base-uri 'none'; form-action 'none'`;

/** Render a report as one self-contained HTML document: inline CSS, JS and SVG, no network. */
export function renderReport(report: Report): string {
  const context = createContext(report, safeTimeZone(String(report.timeZone ?? "UTC")));
  const advice = collectAdvice(context);
  const hasAnalysis = report.narrative !== null && report.narrative !== undefined;

  const body: Array<{ id: string; label: string; content: SafeHtml | null }> = [
    { id: "coverage", label: "Coverage", content: coverageSection(context) },
    { id: "insights-prompt", label: "Add insights", content: hasAnalysis ? null : insightsPromptSection(context) },
    { id: "work", label: "Work", content: workSection(context) },
    { id: "activity", label: "Activity", content: activitySection(context) },
    { id: "usage", label: "Tokens and cost", content: usageSection(context) },
    { id: "wins", label: "What went well", content: winsSection(context) },
    { id: "friction", label: "Friction", content: frictionSection(context, advice) },
    { id: "suggestions", label: "Suggestions", content: suggestionsSection(context, advice) },
    { id: "features", label: "Features", content: featuresSection(context, advice) },
    { id: "horizon", label: "Horizon", content: horizonSection(context) },
    { id: "matrix", label: "Keep your history", content: matrixSection(context) },
  ];
  const present = body.filter((entry) => entry.content !== null);
  const nav: NavItem[] = present.filter((entry) => entry.id !== "insights-prompt").map(({ id, label }) => ({ id, label }));
  const generated = formatDate(report.generatedAt, context.zone);
  const range = rangeText(context);

  const document = html`<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${raw(CSP)}">
<meta name="color-scheme" content="light dark">
<meta name="referrer" content="no-referrer">
<meta name="generator" content="Hindsight">
<title>${range ? `Hindsight · ${range}` : "Hindsight report"}</title>
<style>${raw(STYLES)}</style>
</head>
<body>
<main>
${overviewSection(context, nav)}
${join(present.map((entry) => entry.content))}
</main>
<footer>
<p>Generated by Hindsight${generated ? ` on ${generated}` : ""}. Days and hours are in ${context.zone}.</p>
<p>Everything here was computed on your machine from your local agent history. Nothing in this report was uploaded, and it loads nothing from the network.</p>
</footer>
<script>${raw(SCRIPT)}</script>
</body>
</html>
`;
  return document.value;
}
