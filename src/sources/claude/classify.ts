export function toolCategory(name: string): ToolCategory {
  if (name.startsWith("mcp__")) return "mcp";
  return CATEGORY_BY_TOOL[name] ?? "other";
}

/** `mcp__<server>__<tool>` → server. Claude Code replaces separators in server names, so the first segment is the server. */
export function mcpServer(name: string): string | null {
  if (!name.startsWith("mcp__")) return null;
  const rest = name.slice(5);
  const cut = rest.indexOf("__");
  const server = cut === -1 ? rest : rest.slice(0, cut);
  return server.length > 0 ? server : null;
}

// Ordered: the first matching rule wins, so specific phrasings come before generic ones.
const ERROR_RULES: Array<[RegExp, ToolErrorCategory]> = [
  [/doesn't want to (proceed|take this action)|tool use was rejected|user rejected|rejected by (the )?user|Request interrupted by user/i, "user_rejected"],
  [/permission for this action|permission denied|EACCES|EPERM|operation not permitted|not allowed|requires approval|was denied/i, "permission_denied"],
  [/has not been read yet|modified since (it was )?(last )?read|has been modified|file (was )?changed|unexpectedly modified/i, "file_changed"],
  [/string to replace not found|old_string|no match(es)? found for|found \d+ matches|did not match/i, "edit_mismatch"],
  [/timed? ?out|timeout|deadline exceeded/i, "timeout"],
  [/too large|exceeds (the )?max|maximum allowed (size|tokens)|too long|output limit/i, "too_large"],
  [/no such file|does not exist|ENOENT|file not found|path not found|cannot find/i, "file_not_found"],
  [/exit code\s*\d+|command failed|non-zero exit|returned \d+/i, "command_failed"],
];

// A failing shell command's stderr says "No such file" or "not found" all the
// time; that is still the command failing, so shell errors only get a more
// specific category when the harness itself said so.
const SHELL_RULES: Array<[RegExp, ToolErrorCategory]> = [
  [/^(?:<tool_use_error>)?[^\n]*(doesn't want to (proceed|take this action)|tool use was rejected|Request interrupted by user)/i, "user_rejected"],
  [/^(?:<tool_use_error>)?\s*(Permission for this action|Permission to use|.*requires approval)/i, "permission_denied"],
  [/^(?:<tool_use_error>)?\s*(Command timed out|.*timed out after)/i, "timeout"],
  [/^(?:<tool_use_error>)?\s*(Output too large|.*exceeds (the )?max)/i, "too_large"],
];

export function errorCategory(text: string, toolCategoryValue: ToolCategory): ToolErrorCategory {
  const head = text.slice(0, 600);
  if (toolCategoryValue === "shell") {
    for (const [pattern, category] of SHELL_RULES) {
      if (pattern.test(head)) return category;
    }
    return head.startsWith("<tool_use_error>") ? "other" : "command_failed";
  }
  for (const [pattern, category] of ERROR_RULES) {
    if (pattern.test(head)) return category;
  }
  return "other";
}

// Text that Claude Code writes into "user" lines on the person's behalf.
const INJECTED_PREFIXES = [
  "<local-command-caveat>",
  "<local-command-stdout>",
  "<local-command-stderr>",
  "<system-reminder>",
  "<bash-stdout>",
  "<bash-stderr>",
  "<user-prompt-submit-hook>",
  "<command-message>",
  "This session is being continued from a previous conversation",
  "Caveat: The messages below were generated by the user while running local commands",
  "No response requested.",
];

/**
 * Messages another agent put into the session: the hub, a peer session, a
 * teammate. Only the start of the text is checked: a person quoting
 * `<hc from=...>` mid-sentence, or pasting one inside `<pasted_content>`, is
 * still the person typing.
 */
const AGENT_MESSAGE = new RegExp(
  [
    String.raw`^<hc(?:\s[^>]*)?>`,
    "^Another Claude session sent a message",
    String.raw`^<cross-session-message\b`,
    String.raw`^<agent-message\b`,
    String.raw`^<teammate-message\b`,
  ].join("|"),
);

export function isAgentMessageText(text: string): boolean {
  return AGENT_MESSAGE.test(text.trimStart());
}

/**
 * The harness reporting on the agent's own work: a background command or
 * subagent finishing, a monitor event, the hub saying a peer went idle.
 * Nobody is speaking, so these count as neither the person nor another agent.
 */
const HARNESS_EVENT = /^(?:<task-notification\b|\[Cross-session idle notice\])/;

export function isHarnessEventText(text: string): boolean {
  return HARNESS_EVENT.test(text.trimStart());
}

/** One line that says what a harness event was, for excerpts. Callers scrub and cap it. */
export function harnessEventLine(raw: string, label?: string): string {
  const text = raw.slice(0, 20_000).trim();
  if (text.startsWith("<task-notification")) {
    const tag = (name: string) => new RegExp(`<${name}>([\\s\\S]*?)</${name}>`).exec(text)?.[1]?.trim() ?? "";
    const what = tag("summary") || tag("event") || (tag("status") ? `background task ${tag("status")}` : "background task");
    return `[task notification] ${what}`.replace(/\s+/g, " ");
  }
  const first = text.split("\n", 1)[0] ?? "";
  return (label ? `[${label}] ${first}` : first).replace(/\s+/g, " ");
}

const INTERRUPT = /^\[Request interrupted by user[^\]]*\]$/;

export type PromptKind =
  | { kind: "prompt"; text: string }
  | { kind: "slash"; name: string; args: string }
  | { kind: "bash"; command: string }
  | { kind: "interrupt" }
  | { kind: "agent"; text: string }
  | { kind: "harness"; text: string }
  | { kind: "injected" };

/** Decide what a user-typed-looking string really is. */
export function classifyUserText(raw: string): PromptKind {
  const text = raw.trim();
  if (text === "") return { kind: "injected" };
  if (INTERRUPT.test(text)) return { kind: "interrupt" };
  if (isHarnessEventText(text)) return { kind: "harness", text: harnessEventLine(text) };
  if (isAgentMessageText(text)) return { kind: "agent", text };
  const command = /<command-name>\s*([^<]*?)\s*<\/command-name>/.exec(text);
  if (command && command[1]) {
    const args = /<command-args>([\s\S]*?)<\/command-args>/.exec(text)?.[1]?.trim() ?? "";
    const name = command[1].startsWith("/") ? command[1] : `/${command[1]}`;
    return { kind: "slash", name, args };
  }
  const bash = /^<bash-input>([\s\S]*?)<\/bash-input>/.exec(text);
  if (bash) return { kind: "bash", command: (bash[1] ?? "").trim() };
  for (const prefix of INJECTED_PREFIXES) {
    if (text.startsWith(prefix)) return { kind: "injected" };
  }
  return { kind: "prompt", text };
}

/**
 * Drop heredoc bodies and quoted strings, so a commit message or script that
 * mentions `git push` is not mistaken for running it.
 */
function stripShellData(command: string): string {
  const lines = command.slice(0, 50_000).split("\n");
  const kept: string[] = [];
  let terminator: string | null = null;
  for (const line of lines) {
    if (terminator !== null) {
      if (line.trim() === terminator) terminator = null;
      continue;
    }
    kept.push(line);
    const heredoc = /<<-?\s*(['"]?)([A-Za-z_][\w-]*)\1/.exec(line);
    if (heredoc?.[2]) terminator = heredoc[2];
  }
  return kept.join("\n").replace(/"(?:[^"\\]|\\.)*"|'[^']*'/g, '""');
}

/** Split a shell line into simple commands so `git add . && git commit` counts its commit. */
function simpleCommands(command: string): string[] {
  return stripShellData(command)
    .split(/&&|\|\||;|\||\n|\$\(|`/)
    .map((part) => part.trim())
    .filter(Boolean);
}

// `git [-C dir] [-c k=v] [--flag]... <sub>`
const GIT_SUBCOMMAND = /^(?:\S+=\S*\s+)*(?:sudo\s+)?git((?:\s+(?:-C|-c)\s+\S+|\s+--?[\w-]+(?:=\S+)?)*)\s+([\w-]+)/;

export function gitSubcommands(command: string): string[] {
  const found: string[] = [];
  for (const part of simpleCommands(command)) {
    const match = GIT_SUBCOMMAND.exec(part);
    if (match?.[2]) found.push(match[2]);
  }
  return found;
}

function lines(text: string): string[] {
  if (text === "") return [];
  const out = text.split("\n");
  if (out[out.length - 1] === "") out.pop();
  return out;
}

const MAX_DIFF_LINES = 20_000;

/** Lines added and removed going from `before` to `after`, as a multiset difference (cheap, order-insensitive). */
export function lineDelta(before: string, after: string): { added: number; removed: number } {
  const oldLines = lines(before).slice(0, MAX_DIFF_LINES);
  const newLines = lines(after).slice(0, MAX_DIFF_LINES);
  const counts = new Map<string, number>();
  for (const line of oldLines) counts.set(line, (counts.get(line) ?? 0) + 1);
  let added = 0;
  for (const line of newLines) {
    const left = counts.get(line) ?? 0;
    if (left > 0) counts.set(line, left - 1);
    else added += 1;
  }
  let removed = 0;
  for (const left of counts.values()) removed += left;
  return { added, removed };
}

export function lineCount(text: string): number {
  return Math.min(lines(text).length, MAX_DIFF_LINES);
}

