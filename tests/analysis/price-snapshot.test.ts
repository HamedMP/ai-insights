import { readFileSync } from "node:fs";
import { describe, expect, it } from "vitest";
import { PRICE_SNAPSHOT, PRICES } from "../../src/analysis/prices.generated.js";
import { estimateUsd, PRICING_VERSION } from "../../src/analysis/usage.js";
// @ts-expect-error: a plain ES module script, outside the TypeScript project.
import { generate, pin, readInputs } from "../../scripts/update-prices.mjs";

/** The table as checked by hand against the providers' pricing pages on 18 Nov 2026, before it was generated. */
const VERIFIED = JSON.parse(readFileSync(new URL("./fixtures/verified-prices.json", import.meta.url), "utf8")) as {
  verifiedOn: string;
  snapshot: string;
  prices: Record<string, unknown[]>;
};

describe("price snapshot", () => {
  it("is exactly what the generator makes from the committed snapshot and overrides", () => {
    const committed = readFileSync(new URL("../../src/analysis/prices.generated.ts", import.meta.url), "utf8");
    expect(generate(readInputs()).source).toBe(committed);
  });

  it("keeps every model that was priced on 18 Nov priced", () => {
    const missing = Object.keys(VERIFIED.prices).filter((model) => !(model in PRICES));
    expect(missing).toEqual([]);
  });

  it("reproduces the 18 Nov verified prices exactly while the snapshot is the one they were checked against", () => {
    // A refreshed snapshot fails here on purpose: review the price diff, then record the new snapshot date in the fixture.
    expect(PRICE_SNAPSHOT.date).toBe(VERIFIED.snapshot);
    expect(JSON.parse(JSON.stringify(PRICES))).toEqual(VERIFIED.prices);
  });

  it("derives the pricing version from the snapshot date", () => {
    expect(PRICING_VERSION).toBe(`api-list-${PRICE_SNAPSHOT.date}`);
  });

  it("keeps the automatic reviewer unpriced: OpenAI publishes no price for it", () => {
    expect("codex-auto-review" in PRICES).toBe(false);
    expect(estimateUsd("codex-auto-review", { input: 1000, cachedInput: 0, cacheWrite: 0, output: 10 })).toBeNull();
  });

  it("names its sources and the date they were read", () => {
    const header = readFileSync(new URL("../../src/analysis/prices.generated.ts", import.meta.url), "utf8").split("\n").slice(0, 12).join("\n");
    expect(header).toContain("Generated by `node scripts/update-prices.mjs`");
    expect(header).toContain("https://raw.githubusercontent.com/BerriAI/litellm/");
    expect(header).toContain("https://platform.claude.com/docs/en/about-claude/pricing");
    expect(header).toContain("https://developers.openai.com/api/docs/pricing");
    expect(header).toContain(`Snapshot: ${PRICE_SNAPSHOT.date}`);
  });
});

describe("price generator", () => {
  const inputs = () => readInputs();

  it("lets an override win over the machine-readable source and reports the disagreement", () => {
    const base = inputs();
    const entry = base.snapshot.models["claude-opus-5-5"];
    const changed = { ...base, snapshot: { ...base.snapshot, models: { ...base.snapshot.models, "claude-opus-5-5": { ...entry, input_cost_per_token: 9e-6 } } } };
    const verified = { ...changed, overrides: { ...changed.overrides, models: { ...changed.overrides.models, "claude-opus-5-5": { ...changed.overrides.models["claude-opus-5-5"], standard: { input: 4 } } } } };
    const out = generate(verified);
    expect(out.prices["claude-opus-5-5"][0].standard.rates.input).toBe(4);
    expect(out.disagreements).toContainEqual(expect.objectContaining({ model: "claude-opus-5-5", field: "standard.input", source: 9, used: 4 }));
  });

  it("follows the source when no override pins a value, so a price change shows up in the generated diff", () => {
    const base = inputs();
    const entry = base.snapshot.models["gpt-6.1-sol"];
    const changed = { ...base, snapshot: { ...base.snapshot, models: { ...base.snapshot.models, "gpt-6.1-sol": { ...entry, output_cost_per_token: 12e-6 } } } };
    expect(generate(changed).prices["gpt-6.1-sol"][0].standard.rates.output).toBe(12);
  });

  it("refuses to generate when a model the overrides list is missing from the snapshot and has no hand-written row", () => {
    const base = inputs();
    const { "gpt-6.1-sol": _gone, ...models } = base.snapshot.models;
    expect(() => generate({ ...base, snapshot: { ...base.snapshot, models } })).toThrow(/gpt-6\.1-sol/);
  });

  it("pins only the price fields of the models it prices, in a stable order", () => {
    const upstream = {
      "gpt-6.1-sol": { output_cost_per_token: 1e-5, input_cost_per_token: 2e-6, input_cost_per_token_batches: 1e-6, max_tokens: 128000, mode: "chat" },
      "someone-elses-model": { input_cost_per_token: 1e-6, output_cost_per_token: 1e-6 },
    };
    const { overrides } = inputs();
    const pinned = pin(upstream, overrides, { fetched: "2026-11-18", source: "https://example.test/prices.json", sha256: "0".repeat(64) });
    expect(pinned.models).toEqual({ "gpt-6.1-sol": { input_cost_per_token: 2e-6, output_cost_per_token: 1e-5 } });
    expect(Object.keys(pinned.models["gpt-6.1-sol"])).toEqual(["input_cost_per_token", "output_cost_per_token"]);
  });
});
